export function useLanguage() {
  const [lang, setLang] = useState<Language>(globalLanguage);

  useEffect(() => {
    setLang(globalLanguage);
    const stored = localStorage.getItem("eva-lang") as Language;
    if (stored && (stored === "en" || stored === "fr" || stored === "es")) {
      if (globalLanguage !== stored) {
        globalLanguage = stored;
        listeners.forEach((l) => l(stored));
      }
    }

    const handleChange = (newLang: Language) => {
      setLang(newLang);
    };

    listeners.add(handleChange);
    return () => {
      listeners.delete(handleChange);
    };
  }, []);

  const changeLanguage = (newLang: Language) => {
    if (newLang !== globalLanguage) {
      globalLanguage = newLang;
      localStorage.setItem("eva-lang", newLang);
      listeners.forEach((l) => l(newLang));
    }
  };

  const t = (key: keyof typeof translations.en): string => {
    const activeTranslations = translations[lang] || translations.en;
    return activeTranslations[key] || translations.en[key] || key;
  };

  return {
    language: lang,
    setLanguage: changeLanguage,
    t,
  };
}
